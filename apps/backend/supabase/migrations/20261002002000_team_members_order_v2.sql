update public.team_members t
set sort_order = v.sort_order
from (values
  ('แสน',   10),   -- Founder
  ('เติร์ด',  20),   -- Co-Founder
  ('ก็อต',   30),   -- Co-Founder
  ('พี',     40),
  ('วิน',    50),
  ('เนวิน',  60),
  ('บิว',    70)
) as v(nickname, sort_order)
where t.nickname = v.nickname;
